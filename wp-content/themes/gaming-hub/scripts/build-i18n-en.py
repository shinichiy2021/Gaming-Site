def php_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def main() -> None:
    missing = [k for k in KEYS if k not in EN]
    if missing:
        raise SystemExit(f"Missing {len(missing)} translations, first: {missing[0]!r}")

    merged = dict(EN)
    merged.update(EXTRA)

    lines = [
        "<?php",
        "/**",
        " * Japanese source strings → English.",
        " *",
        " * @package Gaming_Hub",
        " */",
        "",
        "if ( ! defined( 'ABSPATH' ) ) {",
        "	exit;",
        "}",
        "",
        "return array(",
    ]
    for src, dst in merged.items():
        lines.append(f"	'{php_escape(src)}' => '{php_escape(dst)}',")
    lines.append(");")
    lines.append("")

    out = ROOT / "inc" / "i18n-en.php"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({len(merged)} entries)")


if __name__ == "__main__":
    main()
